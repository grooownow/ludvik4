/**
 * Writes src/features/site/case-screens-en.ts: the English screen list of
 * every ludvik4.dev case, sizes read from the files in public/cases/<slug>/en/.
 * Re-run after re-exporting a screen: `pnpm tsx scripts/gen-case-screens-en.ts`.
 * Spec: docs/superpowers/specs/2026-11-17-works-gallery-en.md.
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";

type Spec = {
  kind: "desktop" | "mobile";
  caption: string;
  full: string;
  thumb: string;
  stripThumb?: string;
  squareThumb?: string;
  longThumb?: string;
};

const d = (caption: string, name: string, extra: Partial<Spec> = {}): Spec => ({
  kind: "desktop",
  caption,
  full: `${name}.webp`,
  thumb: `${name}-t.webp`,
  ...extra,
});
const m = (caption: string, name: string, extra: Partial<Spec> = {}): Spec => ({
  ...d(caption, name, extra),
  kind: "mobile",
  ...extra,
});

const SCREENS: Record<string, Spec[]> = {
  smallfriendfiles: [
    d("Landing", "welcome-d"),
    m("Landing", "welcome-m"),
    d("Home", "xgHTM"),
    m("Home", "OS83o"),
    d("Pet passport", "LioTf"),
    m("Pet passport", "U4KOO"),
    d("Document", "doc-d"),
    m("Document", "doc-m"),
    d("Vaccinations", "xLzLo"),
    m("Vaccinations", "P6zcT"),
    d("Document pack", "pack-d"),
    m("Document pack", "pack-m"),
    d("Profile", "prof-d"),
    m("Profile", "prof-m"),
  ],
  gridfin: [
    d("Landing", "landing-d", { stripThumb: "landing-d-s.webp" }),
    m("Landing", "landing-m", {
      full: "landing-m.jpg",
      longThumb: "landing-m-f.webp",
    }),
    d("First screen", "hero-d"),
  ],
  "secret-santa": [
    d("Promo page", "promo-d"),
    m("Promo page", "promo-m", { full: "promo-m.jpg" }),
    d("Profile", "RCoTL", { squareThumb: "RCoTL-sq.webp" }),
    m("Profile", "KjReh"),
    m("Participant's account", "MAQfu"),
    m("Leave a gift", "b4x7S"),
    m("Gift waiting", "pgbnS"),
    m("Guess your Santa", "zY7JF"),
    d("Thank-you wall", "S1a6y", { squareThumb: "S1a6y-sq.webp" }),
    m("Thank-you wall", "z6Qz5"),
    m("Organiser admin", "ThhEp"),
  ],
  "qa-pilot": [d("First screen", "hero-d"), m("First screen", "hero-m")],
};

const root = path.resolve(import.meta.dirname, "..");

function image(slug: string, file: string) {
  const src = `/cases/${slug}/en/${file}`;
  const abs = path.join(root, "public", src);
  if (!existsSync(abs)) throw new Error(`missing screen ${src}`);
  const [width, height] = execFileSync("magick", [
    "identify",
    "-format",
    "%w %h",
    abs,
  ])
    .toString()
    .split(" ")
    .map(Number);
  return { src, width, height };
}

const out: Record<string, unknown[]> = {};
for (const [slug, specs] of Object.entries(SCREENS)) {
  out[slug] = specs.map((s) => ({
    kind: s.kind,
    caption: s.caption,
    full: image(slug, s.full),
    thumb: image(slug, s.thumb),
    ...(s.stripThumb ? { stripThumb: image(slug, s.stripThumb) } : {}),
    ...(s.squareThumb ? { squareThumb: image(slug, s.squareThumb) } : {}),
    ...(s.longThumb ? { longThumb: image(slug, s.longThumb) } : {}),
  }));
}

writeFileSync(
  path.join(root, "src/features/site/case-screens-en.ts"),
  `// Generated by scripts/gen-case-screens-en.ts — do not edit by hand.
import type { Screen } from "./case-gallery";

export const caseScreensEn = ${JSON.stringify(out, null, 2)} satisfies Record<string, Screen[]>;
`,
);
