export type PricingPackage = {
  name: string;
  price: string;
  /** A real, dated launch offer: the regular price, shown struck out. */
  oldPrice?: string;
  /** The offer's terms, e.g. "Цена до 31 декабря". */
  promo?: string;
  /** A quiet line under a "from" price, e.g. what the final price depends on. */
  priceNote?: string;
  term: string;
  /** "Всё из Базового, плюс:" — a package lists only what it adds. */
  includes?: string;
  items: string[];
  featured?: boolean;
};

export type PricingService = {
  /** Key of the tab; its own page is /uslugi/<slug> (PRICING_SLUGS). */
  id: string;
  /** The tab's own URL segment: /uslugi/<slug>. */
  slug: string;
  /** <title> and description of the tab's own page. */
  seoTitle: string;
  hall: string;
  name: string;
  lead: string;
  /** "From" price: the basic package; shown on the home, not on this page. */
  from: string;
  /** What the client brings — kept short: little is needed from them. */
  needs: string[];
  /** What they get, put as plain positive statements. */
  benefits: { title: string; text: string }[];
  packages: PricingPackage[];
  /** "Например": what the service can be, told through real cases. */
  examples?: {
    title: string;
    text: string;
    /** A link on a phrase inside the text (e.g. our own product's name). */
    link?: { text: string; href: string };
    /** The whole title as a link. */
    href?: string;
  }[];
  /** Live effects to touch ("Потрогайте сами") — the animation tab. */
  gallery?: boolean;
  /** "Под капотом": the technical side, for those who ask. */
  tech?: { title: string; text: string }[];
  /** "Not sure this is the right service?" — pointers to neighbouring tabs. */
  related?: { text: string; label: string; href: string }[];
  /** What every package includes — said once, under the packages. */
  everywhere: string[];
  /** What is paid apart, after that line. */
  everywhereNote: string;
  /** The service's own detailed page, where one exists. */
  detailHref?: string;
};

function packages(from: string): PricingPackage[] {
  // Package prices are fixed; "from" is the basic package's price.
  const stub = (n: number) =>
    Array.from({ length: n }, () => "Пункт пакета — заглушка");
  return [
    {
      name: "Базовый",
      price: from.replace(/^от /, ""),
      term: "срок: N недель",
      items: stub(4),
    },
    {
      name: "Расширенный",
      price: "XX XXX ₽",
      term: "срок: N недель",
      includes: "Всё из Базового, плюс:",
      items: stub(5),
      featured: true,
    },
    {
      name: "Максимальный",
      price: "XXX XXX ₽",
      term: "срок: N недель",
      includes: "Всё из Расширенного, плюс:",
      items: stub(6),
    },
  ];
}

